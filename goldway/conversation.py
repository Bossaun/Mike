"""Small deterministic answers; general model replies are a separate field."""
import re

GENERAL_PATTERN = r'общаться|что (?:ты )?умеешь|кто ты|как тебя зовут|как дела'


def basic_reply(text):
    question=' '.join(text.casefold().split()).strip(' ?!.')
    if question in ('а с тобой можно общаться','с тобой можно общаться','можно общаться','можно'):
        return 'Да, можно общаться со мной обычным текстом. Задайте вопрос, предложите идею, пришлите планёрку или расскажите о результате работы. Если нужно уточнить задачу, назовите её или ответьте на карточку.'
    if question in ('что ты умеешь','что умеешь','кто ты','как тебя зовут') or re.fullmatch(r'как (?:тобой|вами|ботом|этим ботом|такой) пользоваться',question):
        return 'Я помощник GOLDWAY. Можно задать вопрос, предложить идею или прислать текст планёрки — выделю задачи и покажу черновики для подтверждения руководителем. О работе расскажите своими словами: что готово, что мешает и какой следующий шаг. Задачу можно назвать или ответить на её карточку. Команды не нужны.'
    return None


def is_general(text):
    return basic_reply(text) is not None or bool(re.search(GENERAL_PATTERN,text.casefold()))
